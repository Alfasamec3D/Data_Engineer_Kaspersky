#!/usr/bin/env bash
# Generates requirements.txt with strictly pinned versions and hashes
# (all transitive dependencies included) for the main image and for the downloader.
# Requires uv (https://docs.astral.sh/uv/), python3 and internet access.
#
#   ./scripts/lock.sh                      # vLLM 0.27.1
#   VLLM_VERSION=0.28.0 ./scripts/lock.sh  # another version (>= 0.27.0)
#   GITHUB_TOKEN=... ./scripts/lock.sh     # optional, avoids GitHub API rate limits
#
# The exact CPU wheel file name (including the manylinux tag, which differs between
# vLLM releases) is NOT hardcoded: it is read from the assets of the GitHub release.
set -euo pipefail
cd "$(dirname "$0")/.."

VLLM_VERSION="${VLLM_VERSION:-0.27.1}"
if [[ "$(printf '%s\n0.27.0\n' "$VLLM_VERSION" | sort -V | head -1)" != "0.27.0" ]]; then
  echo "VLLM_VERSION must be >= 0.27.0" >&2; exit 1
fi

auth=()
[[ -n "${GITHUB_TOKEN:-}" ]] && auth=(-H "Authorization: Bearer ${GITHUB_TOKEN}")

release_json="$(mktemp)"
trap 'rm -f "$release_json"' EXIT
curl -fsSL "${auth[@]}" \
  "https://api.github.com/repos/vllm-project/vllm/releases/tags/v${VLLM_VERSION}" \
  -o "$release_json"

# pick the x86_64 CPU wheel among the release assets
wheel_url="$(python3 -I - "$release_json" <<'EOF'
import json, re, sys

assets = json.load(open(sys.argv[1])).get("assets", [])
pattern = re.compile(r"\+cpu-.*manylinux_[0-9_]+_x86_64\.whl$")
matches = [a for a in assets if pattern.search(a["name"])]
if not matches:
    names = "\n".join("  " + a["name"] for a in assets) or "  (no assets)"
    sys.exit("No x86_64 CPU wheel among the release assets:\n" + names)
print(matches[0]["browser_download_url"])
EOF
)"
echo "Using CPU wheel: ${wheel_url}"

cat > requirements.in <<EOF
# GENERATED by scripts/lock.sh, do not edit by hand.
# Top-level dependency only; the full pin (with hashes) is requirements.txt.
# vLLM version must be >= 0.27.0 (assignment requirement).
vllm @ ${wheel_url}
EOF

# --python-platform: resolve for the target image (Ubuntu 24.04, x86_64, Python 3.12),
# regardless of where this script runs (even macOS).
uv pip compile requirements.in \
  --output-file requirements.txt \
  --generate-hashes \
  --python-version 3.12 \
  --python-platform x86_64-manylinux_2_35 \
  --extra-index-url https://download.pytorch.org/whl/cpu \
  --index-strategy unsafe-best-match \
  --emit-index-url

uv pip compile downloader/requirements.in \
  --output-file downloader/requirements.txt \
  --generate-hashes \
  --python-version 3.12 \
  --python-platform x86_64-manylinux_2_28

echo "OK: requirements.in, requirements.txt and downloader/requirements.txt updated. Commit them."
